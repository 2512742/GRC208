import { ArrowDownTrayIcon, PrinterIcon } from "@heroicons/react/24/outline";
import { useQuery } from "@tanstack/react-query";
import { useState } from "react";

import { api, download } from "../api/client";
import { useServices } from "../api/queries";
import type { Overview, Totals } from "../api/types";
import { useAuth } from "../auth/AuthContext";
import { ScoreBadge, StatusChip } from "../components/risk";
import { useToast } from "../components/Toast";
import { ErrorState, Loading, PageHeader } from "../components/ui";
import { BANDS, compactNaira, titleCase } from "../lib/format";
import { formatDate, formatDateTime, zoneAbbreviation } from "../lib/time";

export default function ReportsPage() {
  const { me, zone } = useAuth();
  const toast = useToast();
  const services = useServices();
  const [filters, setFilters] = useState({ service_id: "", band: "", above_appetite: "" });
  const [busy, setBusy] = useState<"" | "csv" | "pdf">("");
  const query = {
    service_id: filters.service_id || undefined,
    band: filters.band || undefined,
    above_appetite: filters.above_appetite || undefined,
  };
  const q = useQuery({ queryKey: ["report", query], queryFn: () => api.get<Overview>("/reports/management", query) });
  const generatedAt = new Date().toISOString();

  async function exportAs(kind: "csv" | "pdf") {
    setBusy(kind);
    try {
      await download(`/reports/management.${kind}`, { ...query, tz: zone });
      toast.success(`Management report (${kind.toUpperCase()}) downloaded.`);
    } catch (e) {
      toast.error(e);
    } finally {
      setBusy("");
    }
  }

  const totals = q.data?.totals as unknown as Totals | undefined;
  return (
    <>
      <PageHeader
        eyebrow="Reporting"
        title="Management report"
        description="Filter, preview, then export. Exports are stamped with who generated them and when, and logged."
        actions={
          <>
            <button type="button" className="btn-secondary" onClick={() => window.print()}>
              <PrinterIcon className="h-4 w-4" aria-hidden /> Print
            </button>
            <button type="button" className="btn-secondary" disabled={!!busy} onClick={() => exportAs("csv")}>
              <ArrowDownTrayIcon className="h-4 w-4" aria-hidden /> {busy === "csv" ? "Preparing…" : "CSV"}
            </button>
            <button type="button" className="btn-primary" disabled={!!busy} onClick={() => exportAs("pdf")}>
              <ArrowDownTrayIcon className="h-4 w-4" aria-hidden /> {busy === "pdf" ? "Preparing…" : "PDF"}
            </button>
          </>
        }
      />
      <div className="no-print card mb-4 grid grid-cols-1 gap-3 p-3 sm:grid-cols-3">
        <select aria-label="Service" className="input" value={filters.service_id} onChange={(e) => setFilters({ ...filters, service_id: e.target.value })}>
          <option value="">All services</option>
          {(services.data ?? []).map((s) => (
            <option key={s.id} value={s.id}>
              {s.code} {s.name}
            </option>
          ))}
        </select>
        <select aria-label="Band" className="input" value={filters.band} onChange={(e) => setFilters({ ...filters, band: e.target.value })}>
          <option value="">All bands</option>
          {BANDS.map((b) => (
            <option key={b} value={b}>
              {titleCase(b)}
            </option>
          ))}
        </select>
        <select aria-label="Appetite" className="input" value={filters.above_appetite} onChange={(e) => setFilters({ ...filters, above_appetite: e.target.value })}>
          <option value="">Above and within appetite</option>
          <option value="true">Above appetite only</option>
          <option value="false">Within appetite only</option>
        </select>
      </div>

      {q.isLoading ? (
        <Loading />
      ) : q.error || !q.data || !totals ? (
        <ErrorState error={q.error} retry={() => q.refetch()} />
      ) : (
        <article className="card p-6 print:border-0 print:p-0">
          <header className="border-b border-line pb-3">
            <div className="label-caps">The Alajo · Cyber risk management report</div>
            <h2 className="mt-1 text-primary">Risk register summary</h2>
            <p className="mt-1 text-xs text-muted">
              Generated by {me?.full_name} ({me?.role}) on {formatDateTime(generatedAt, zone)}. Times shown in{" "}
              {zoneAbbreviation(zone)}; deadlines and expiry evaluated in WAT (Africa/Lagos). Appetite threshold:{" "}
              {q.data.appetite_threshold}.
            </p>
          </header>
          <section className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
            {[
              ["Risks", totals.risks],
              ["Above appetite", totals.above_appetite],
              ["Overdue actions", totals.overdue_actions],
              ["Open treatment cost", compactNaira(q.data.open_treatment_cost_ngn)],
              ["Pending acceptances", totals.pending_acceptances],
              ["Expired acceptances", totals.expired_acceptances],
              ["Awaiting reassessment", totals.awaiting_reassessment],
              ["Reviews due", totals.reviews_due],
            ].map(([label, value]) => (
              <div key={label} className="border border-line p-2">
                <div className="label-caps text-[10px]">{label}</div>
                <div className="mono-data text-lg font-bold">{value}</div>
              </div>
            ))}
          </section>
          <section className="mt-6">
            <h3 className="label-caps mb-2 text-ink">Risks ({q.data.risks?.length ?? 0})</h3>
            <div className="overflow-x-auto">
              <table className="table-base text-xs">
                <thead>
                  <tr>
                    <th>ID</th>
                    <th>Risk</th>
                    <th>Score</th>
                    <th>Owner</th>
                    <th>Status</th>
                    <th>Strategy</th>
                    <th>Next review</th>
                  </tr>
                </thead>
                <tbody>
                  {(q.data.risks ?? []).map((r) => (
                    <tr key={r.id}>
                      <td className="mono-data">{r.risk_code}</td>
                      <td>{r.title}</td>
                      <td>
                        <ScoreBadge score={r.current} />
                      </td>
                      <td>{r.owner.full_name}</td>
                      <td>
                        <StatusChip status={r.display_status} />
                      </td>
                      <td>{titleCase(r.strategy)}</td>
                      <td className="whitespace-nowrap">{formatDate(r.next_review_date)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </section>
          {q.data.overdue_actions.length > 0 && (
            <section className="mt-6">
              <h3 className="label-caps mb-2 text-ink">Overdue actions</h3>
              <ul className="list-disc pl-5 text-sm">
                {q.data.overdue_actions.map((a) => (
                  <li key={a.action_id}>
                    <span className="mono-data">{a.action_code}</span> ({a.risk_code}) {a.title}: due {formatDate(a.due_date)},{" "}
                    {a.days_overdue} days overdue, owner {a.owner}
                  </li>
                ))}
              </ul>
            </section>
          )}
          <footer className="mt-6 border-t border-line pt-2 text-[11px] text-muted">
            RiskTrack · The Alajo is a fictional organisation (GRC208 capstone). Export logged in the audit trail.
          </footer>
        </article>
      )}
    </>
  );
}
