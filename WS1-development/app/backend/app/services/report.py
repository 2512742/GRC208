"""Management risk report exports (brief feature 6; deliverable 5): CSV and PDF.

Both are stamped with who generated them, when (in the generator's chosen zone and in UTC) and
which filters applied, and both state that deadlines are evaluated in the organisation's zone.
"""

from __future__ import annotations

import csv
import io
from dataclasses import dataclass
from datetime import datetime
from zoneinfo import ZoneInfo

from fpdf import FPDF

from app.services.dashboard import Overview

# Spreadsheet apps execute cells starting with these as formulas (CSV injection).
FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


@dataclass(frozen=True)
class Stamp:
    generated_by: str
    generated_at_utc: datetime
    display_zone: str  # IANA zone used for the human-readable time
    org_zone: str
    filters: str

    @property
    def local_time(self) -> str:
        local = self.generated_at_utc.astimezone(ZoneInfo(self.display_zone))
        return f"{local:%d %b %Y, %H:%M} {local.tzname()}"

    @property
    def utc_time(self) -> str:
        return f"{self.generated_at_utc:%Y-%m-%dT%H:%M:%SZ}"

    @property
    def lines(self) -> list[str]:
        org = datetime.now(ZoneInfo(self.org_zone)).tzname()
        return [
            f"Generated by {self.generated_by} on {self.local_time} ({self.utc_time})",
            f"Deadlines and expiry evaluated in {self.org_zone} ({org})",
            f"Filters: {self.filters or 'none (whole register)'}",
        ]


def safe_cell(value: object) -> object:
    if isinstance(value, str) and value.startswith(FORMULA_PREFIXES):
        return "'" + value
    return value


def to_csv(data: Overview, stamp: Stamp) -> str:
    out = io.StringIO()
    for line in stamp.lines:
        out.write(f"# {line}\n")
    writer = csv.writer(out)
    writer.writerow(
        [
            "risk_code",
            "title",
            "owner",
            "services",
            "assets",
            "status",
            "likelihood",
            "impact",
            "score",
            "band",
            "above_appetite",
            "original_score",
            "strategy",
            "open_actions",
            "overdue_actions",
            "next_review_date",
            "acceptance_expiry",
            "generated_at_utc",
        ]
    )
    for r in data.risks:
        current = r.current
        writer.writerow(
            [
                safe_cell(v)
                for v in (
                    r.risk_code,
                    r.title,
                    r.owner.full_name,
                    ";".join(r.services),
                    ";".join(a.asset_code for a in r.assets),
                    r.display_status,
                    current.likelihood if current else "",
                    current.impact if current else "",
                    current.score if current else "",
                    current.band.value if current else "",
                    "yes" if current and current.above_appetite else "no",
                    r.original_score if r.original_score is not None else "",
                    r.strategy or "",
                    r.open_actions,
                    r.overdue_actions,
                    r.next_review_date or "",
                    r.acceptance_expiry or "",
                    stamp.utc_time,
                )
            ]
        )
    return out.getvalue()


# ── PDF ────────────────────────────────────────────────────────────────────────────────────

LATIN1_REPLACEMENTS = {
    "×": "x",
    "→": "->",
    "₦": "NGN ",
    "–": "-",
    "—": "-",
    "’": "'",
    "‘": "'",
    "“": '"',
    "”": '"',
    "…": "...",
}


def latin1(text: object) -> str:
    """The PDF's built-in fonts cover Latin-1 only."""
    value = str(text)
    for char, replacement in LATIN1_REPLACEMENTS.items():
        value = value.replace(char, replacement)
    return value.encode("latin-1", "replace").decode("latin-1")


class ReportPDF(FPDF):
    def __init__(self, stamp: Stamp) -> None:
        super().__init__(orientation="portrait", unit="mm", format="A4")
        self.stamp = stamp
        self.set_auto_page_break(auto=True, margin=15)
        self.set_title("The Alajo - Management Risk Report")
        self.set_author(latin1(stamp.generated_by))

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Helvetica", size=8)
        self.cell(
            0,
            6,
            latin1(
                f"RiskTrack - The Alajo (fictional) - {self.stamp.utc_time} - "
                f"page {self.page_no()}/{{nb}}"
            ),
            align="C",
        )

    def heading(self, text: str) -> None:
        self.ln(3)
        self.set_font("Helvetica", "B", 12)
        self.cell(0, 8, latin1(text), new_x="LMARGIN", new_y="NEXT")
        self.set_font("Helvetica", size=9)

    def table(self, headers: list[str], widths: list[float], rows: list[list[object]]) -> None:
        self.set_font("Helvetica", "B", 8)
        for header, width in zip(headers, widths, strict=True):
            self.cell(width, 6, latin1(header), border=1)
        self.ln()
        self.set_font("Helvetica", size=8)
        if not rows:
            self.cell(sum(widths), 6, "None.", border=1, new_x="LMARGIN", new_y="NEXT")
            return
        for row in rows:
            for value, width in zip(row, widths, strict=True):
                text = latin1(value)
                max_chars = int(width / 1.6)
                if len(text) > max_chars:
                    text = text[: max_chars - 1] + "..."
                self.cell(width, 6, text, border=1)
            self.ln()


def to_pdf(data: Overview, stamp: Stamp) -> bytes:
    pdf = ReportPDF(stamp)
    pdf.alias_nb_pages()
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "The Alajo - Management Risk Report", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", size=9)
    for line in stamp.lines:
        pdf.cell(0, 5, latin1(line), new_x="LMARGIN", new_y="NEXT")

    t = data.totals
    pdf.heading("1. Summary")
    pdf.multi_cell(
        0,
        5,
        latin1(
            f"{t['risks']} risks in scope, {t['above_appetite']} above the appetite threshold "
            f"(score {data.appetite_threshold} or more). {t['open_actions']} treatment actions are "
            f"open, {t['overdue_actions']} overdue. {t['pending_acceptances']} acceptance requests "
            f"await a decision and {t['expired_acceptances']} acceptance(s) have expired. "
            f"{t['awaiting_reassessment']} risk(s) await reassessment and {t['reviews_due']} "
            f"review(s) are due within the warning window. Open treatment cost: NGN "
            f"{data.open_treatment_cost_ngn:,.2f}."
        ),
        new_x="LMARGIN",
        new_y="NEXT",
    )
    pdf.table(
        ["Low", "Medium", "High", "Critical"],
        [40, 40, 40, 40],
        [[data.by_band[b] for b in ("low", "medium", "high", "critical")]],
    )

    pdf.heading("2. Heat map (current scores; rows = likelihood, columns = impact)")
    grid = {(c.likelihood, c.impact): c.count for c in data.heat_map_current}
    pdf.table(
        ["L \\ I", "1", "2", "3", "4", "5"],
        [20, 20, 20, 20, 20, 20],
        [[str(lk)] + [grid[(lk, im)] or "" for im in range(1, 6)] for lk in range(5, 0, -1)],
    )

    pdf.heading(f"3. Risks above appetite ({len(data.above_appetite)})")
    pdf.table(
        ["Code", "Title", "Owner", "Score", "Band", "Status"],
        [16, 74, 36, 12, 18, 34],
        [
            [
                r.risk_code,
                r.title,
                r.owner.full_name,
                r.current.score if r.current else "",
                r.current.band.value if r.current else "",
                r.display_status,
            ]
            for r in data.above_appetite
        ],
    )

    pdf.heading(f"4. Overdue treatment actions ({len(data.overdue_actions)})")
    pdf.table(
        ["Action", "Risk", "Title", "Owner", "Due", "Days"],
        [16, 16, 80, 36, 22, 12],
        [
            [o.action_code, o.risk_code, o.title, o.owner, o.due_date, o.days_overdue]
            for o in data.overdue_actions
        ],
    )

    pdf.heading("5. Risk acceptances")
    pdf.table(
        ["Risk", "Title", "Status", "Requested by", "Decided by", "Expiry"],
        [16, 60, 26, 30, 30, 20],
        [
            [
                a.risk_code,
                a.risk_title,
                "expired" if a.expired else a.status,
                a.requested_by,
                a.decided_by or "",
                a.expiry_date or "",
            ]
            for a in data.acceptances
        ],
    )

    pdf.heading(f"6. Reviews due ({len(data.upcoming_reviews)})")
    pdf.table(
        ["Code", "Title", "Owner", "Review date"],
        [16, 100, 40, 26],
        [
            [r.risk_code, r.title, r.owner.full_name, r.next_review_date]
            for r in data.upcoming_reviews
        ],
    )

    pdf.heading("7. By business service")
    pdf.table(
        ["Service", "Risks", "Above appetite", "Highest score"],
        [80, 25, 35, 30],
        [
            [f"{s['code']} {s['name']}", s["risks"], s["above_appetite"], s["highest_score"] or ""]
            for s in data.by_service
        ],
    )

    pdf.heading("8. Regulatory exposure (risks linked to each regime)")
    pdf.table(
        ["Regime", "Risks", "Above appetite"],
        [60, 30, 35],
        [[e["regime"], e["risks"], e["above_appetite"]] for e in data.regulatory_exposure],
    )

    pdf.add_page()
    pdf.heading(f"Appendix: risk register ({len(data.risks)})")
    pdf.table(
        ["Code", "Title", "Owner", "Orig.", "Now", "Band", "Strategy", "Status"],
        [14, 62, 30, 11, 11, 16, 17, 29],
        [
            [
                r.risk_code,
                r.title,
                r.owner.full_name,
                r.original_score if r.original_score is not None else "",
                r.current.score if r.current else "",
                r.current.band.value if r.current else "",
                r.strategy or "",
                r.display_status,
            ]
            for r in data.risks
        ],
    )
    return bytes(pdf.output())
